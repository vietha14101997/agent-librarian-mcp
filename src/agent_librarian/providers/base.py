"""Closed provider contracts; never a generic administration or execution API."""
from typing import Protocol

class ResearchProvider(Protocol):
    def list_notebooks(self) -> dict: ...
    def get_notebook(self,notebook_id:str) -> dict: ...
    def query(self,notebook_id:str,query:str,source_ids:list[str]) -> dict: ...
    def get_source(self,notebook_id:str,source_id:str) -> dict: ...
    def close(self) -> None: ...

class RemoteIdentityInventory(Protocol):
    """Future inventory/attestation adapter only; no add/update/delete interface."""
    def verified_identity_snapshot(self) -> dict: ...
